// Generates a self-contained KaTeX stylesheet with base64-embedded woff2 fonts.
// The app uses this file both for on-screen rendering and for self-contained exports,
// so math looks identical everywhere and exports work offline.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const katexDist = join(root, "node_modules", "katex", "dist");
const fontsDir = join(katexDist, "fonts");
const outFile = join(root, "src", "styles", "katex-inline.generated.css");

let css = readFileSync(join(katexDist, "katex.min.css"), "utf8");
const fonts = new Map(
  readdirSync(fontsDir)
    .filter((name) => name.endsWith(".woff2"))
    .map((name) => [name, readFileSync(join(fontsDir, name)).toString("base64")]),
);

let embedded = 0;
css = css.replace(/url\((["']?)fonts\/([^"')]+?\.woff2)\1\)/g, (_match, _quote, file) => {
  const data = fonts.get(file);
  if (!data) return _match;
  embedded += 1;
  return `url("data:font/woff2;base64,${data}") format("woff2")`;
});

// Drop woff/ttf fallbacks: every modern WebView supports woff2.
css = css.replace(/,\s*url\((["']?)fonts\/[^"')]+?\.(?:woff|ttf)\1\)\s*format\(["'](?:woff|truetype)["']\)/g, "");

const banner = `/* Generated by scripts/inline-katex-fonts.mjs. Do not edit. */\n`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner + css, "utf8");
console.log(`[katex] embedded ${embedded} woff2 fonts -> ${outFile}`);
